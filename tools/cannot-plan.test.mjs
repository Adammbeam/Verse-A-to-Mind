// The 1000-item plan must stay exactly 1000, distinct, sourced from real repo records, and installable.
// Run: node --test tools/cannot-plan.test.mjs
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { plan } from './cannot-plan.mjs';

const read = (f) => readFileSync(new URL('../' + f, import.meta.url), 'utf8');

test('the plan is 1000 distinct rows, each with an install path, a test and a real source', () => {
  const rows = plan({ capability: read('docs/capability-gaps.md'), gaps: read('docs/GAPS.md'), handoffs: read('docs/HANDOFF-GAPS.md') });
  assert.equal(rows.length, 1000);
  const keys = rows.map((r) => r.thing.toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim());
  assert.equal(new Set(keys).size, 1000, 'no repeated thing');
  for (const r of rows) {
    assert.ok(r.thing && r.where && r.install && r.test && r.source && r.why, JSON.stringify(r));
    assert.match(r.test, /\.test\.mjs/, r.test);
  }
  for (const k of ['capability', 'gap', 'handoff', 'outside', 'salvage', 'lab']) assert.ok(rows.some((r) => r.kind === k), k + ' is in the plan');
  assert.ok(rows.every((r, i) => i === 0 || rows[i - 1].cost <= r.cost), 'smallest installs first');
});

test('the committed document has the same 1000 rows and cites files that exist', () => {
  const doc = read('docs/CANNOT-1000.md');
  assert.match(doc, /^# 1000 things Verse cannot do yet/m);
  assert.equal((doc.match(/^\| \d+ \|/gm) || []).length, 1000);
  assert.match(doc, /Generated by `node tools\/cannot-plan\.mjs --write`/);
  for (const f of ['docs/capability-gaps.md', 'docs/GAPS.md', 'docs/HANDOFF-GAPS.md', 'domains/autosalvage.outside.json', 'resources/salvage-github.json', 'void-live-deploy/salvage.json', 'void-live-deploy/lab/catalog.json', 'void-live-deploy/skills/index.json']) assert.ok(read(f), f);
});
